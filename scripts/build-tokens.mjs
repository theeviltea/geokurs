// Builds src/theme/tokens.css + src/theme/tokens.ts from design/tokens.json (Geokurs Design System export).
// Run: npm run tokens
import { readFileSync, writeFileSync } from 'node:fs';

const src = JSON.parse(readFileSync(new URL('../design/tokens.json', import.meta.url), 'utf8'));
const colors = Object.fromEntries(src.color.tokens.map((t) => [t.name, t.value]));
const resolve = (v) => v.replace(/\{([^}]+)\}/g, (_, k) => resolve(colors[k]));
for (const k of Object.keys(colors)) colors[k] = resolve(colors[k]);
const spacing = Object.fromEntries(src.spacing.tokens.map((t) => [t.name, t.value]));
const radius = Object.fromEntries(src.radius.tokens.map((t) => [t.name, t.value]));

const lines = [
  ...Object.entries(colors).map(([k, v]) => `  --c-${k}: ${v};`),
  ...Object.entries(spacing).map(([k, v]) => `  --${k}: ${v};`),
  ...Object.entries(radius).map(([k, v]) => `  --${k}: ${v};`),
  `  --font-display: ${src.type.families.display};`,
  `  --font-text: ${src.type.families.text};`,
];
const header = '/* GENERATED by scripts/build-tokens.mjs from design/tokens.json — do not edit by hand. */\n';
writeFileSync(new URL('../src/theme/tokens.css', import.meta.url), `${header}:root {\n${lines.join('\n')}\n}\n`);

const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const map = (o) => Object.fromEntries(Object.entries(o).map(([k, v]) => [camel(k), v]));
writeFileSync(
  new URL('../src/theme/tokens.ts', import.meta.url),
  `${header.replace('/*', '//').replace(' */', '')}export const colors = ${JSON.stringify(map(colors), null, 2)} as const;\n\nexport const spacing = ${JSON.stringify(map(spacing), null, 2)} as const;\n\nexport const radius = ${JSON.stringify(map(radius), null, 2)} as const;\n`,
);
console.log('tokens: %d colors, %d spacing, %d radius', Object.keys(colors).length, Object.keys(spacing).length, Object.keys(radius).length);
